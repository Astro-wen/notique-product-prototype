#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath, pathToFileURL } from "node:url";

import {
  REALTOR_AB_SCHEMA_VERSION,
  buildScoredComparison,
} from "./lib/realtor-draft-context-ab.mjs";

const REPOSITORY_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

function usage() {
  return `Usage:
  node scripts/score-realtor-draft-context-ab.mjs --run-dir=<path> [--output=<path>]

The run directory must contain manifest.json, both arm.json files, and the two completed
adjudication files generated by run-realtor-draft-context-ab.mjs. This command is offline:
it never calls a model, a server, or production.`;
}

export function parseArgs(argv) {
  let runDirectory = null;
  let outputPath = null;
  let help = false;
  for (const arg of argv) {
    if (arg === "--help") help = true;
    else if (arg.startsWith("--run-dir=")) runDirectory = arg.slice("--run-dir=".length);
    else if (arg.startsWith("--output=")) outputPath = arg.slice("--output=".length);
    else throw new Error(`Unknown argument: ${arg}`);
  }
  if (!help && !runDirectory?.trim()) throw new Error("--run-dir is required.");
  const resolvedDirectory = runDirectory ? path.resolve(runDirectory) : null;
  return {
    help,
    runDirectory: resolvedDirectory,
    outputPath: outputPath?.trim()
      ? path.resolve(outputPath)
      : resolvedDirectory ? path.join(resolvedDirectory, "score.json") : null,
  };
}

async function json(filePath) {
  return JSON.parse(await readFile(filePath, "utf8"));
}

async function main() {
  const options = parseArgs(process.argv.slice(2));
  if (options.help) {
    process.stdout.write(`${usage()}\n`);
    return;
  }
  const manifest = await json(path.join(options.runDirectory, "manifest.json"));
  if (manifest.schemaVersion !== REALTOR_AB_SCHEMA_VERSION) {
    throw new Error("Unsupported Realtor Draft Context A/B manifest.");
  }
  const [control, treatment, controlAdjudication, treatmentAdjudication, groundTruth, actionGroundTruth] =
    await Promise.all([
      json(path.join(options.runDirectory, manifest.arms.control.path)),
      json(path.join(options.runDirectory, manifest.arms.treatment.path)),
      json(path.join(options.runDirectory, manifest.adjudication.control)),
      json(path.join(options.runDirectory, manifest.adjudication.treatment)),
      json(path.resolve(REPOSITORY_ROOT, manifest.fixture.groundTruthPath)),
      json(path.resolve(REPOSITORY_ROOT, manifest.fixture.actionGroundTruthPath)),
    ]);
  const report = buildScoredComparison({
    control,
    treatment,
    controlAdjudication,
    treatmentAdjudication,
    groundTruth,
    actionGroundTruth,
  });
  await writeFile(options.outputPath, `${JSON.stringify(report, null, 2)}\n`, {
    encoding: "utf8",
    flag: "wx",
  });
  process.stdout.write([
    `Score: ${options.outputPath}`,
    `Draft Context enable recommendation: ${report.enableDraftContext ? "YES" : "NO"}`,
    `Treatment quality gates: ${report.treatment.gates.pass ? "PASS" : "FAIL"}`,
    `Token increase: ${report.comparison.tokenIncrease == null ? "unknown" : `${(report.comparison.tokenIncrease * 100).toFixed(1)}%`}`,
    `Fact-stage token increase: ${report.comparison.factTokenIncrease == null ? "unknown" : `${(report.comparison.factTokenIncrease * 100).toFixed(1)}%`}`,
    "",
  ].join("\n"));
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((error) => {
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
    process.exitCode = 1;
  });
}
